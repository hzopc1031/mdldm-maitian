import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {prepColumns,prepColumn,reclassifyColumns} from '../src/prep-columns.mjs';
import {normalizePrep} from '../src/publish-prep.mjs';
import {prepStatus} from '../src/prep-status.mjs';
const names=prepColumns.map(c=>c.name);
assert.deepEqual(names,['AI热点新闻','AI实战详解']);
for(const bad of ['',null,'AI新闻','每日 AI 精选','AI人物动态','AI与科技热点','测试',' AI热点新闻 '])assert.throws(()=>prepColumn(bad),/栏目/);
assert.throws(()=>normalizePrep({platform:'x',content:'新闻',source:{project:'test',column:'AI新闻',runId:'1'}}),/栏目/);
const db=new DatabaseSync(':memory:');db.exec('CREATE TABLE publish_posts(id TEXT PRIMARY KEY,record TEXT NOT NULL);CREATE TABLE publish_preparations(id TEXT PRIMARY KEY,record TEXT NOT NULL)');
const save=(t,r)=>db.prepare(`INSERT INTO ${t} VALUES (?,?)`).run(r.id,JSON.stringify(r));
const read=(t,id)=>JSON.parse(db.prepare(`SELECT record FROM ${t} WHERE id=?`).get(id).record);
const actor={runtime:'codex',sessionId:'columns-fixture'},unknown={id:'linked',source:{project:'old',column:'旧栏目',runId:'one'},state:'unknown',checkedDigest:'unchanged',error:'original failure',evidence:{url:'https://example.test/old'}};
save('publish_preparations',unknown);save('publish_preparations',{id:'nosource',state:'draft_saved',test:true});
save('publish_posts',{id:'post',column:'旧栏目',revision:3,master:{title:'工具'},editions:{x:{preparationId:'linked'}},operations:[]});
const assignment={kind:'post',id:'post',column:names[1],expectedColumn:'旧栏目'};
assert.throws(()=>reclassifyColumns(db,[assignment,{kind:'legacy',id:'missing',column:names[0],expectedColumn:null}],actor),/不存在/);
assert.equal(read('publish_posts','post').column,'旧栏目','整批失败必须回滚');
assert.throws(()=>reclassifyColumns(db,[{...assignment,expectedColumn:'已被别人改过'}],actor),/其他操作/);
assert.throws(()=>reclassifyColumns(db,[assignment,assignment],actor),/重复/);
const result=reclassifyColumns(db,[assignment,{kind:'legacy',id:'nosource',column:names[1],expectedColumn:null}],actor);
assert.equal(result.updates.length,3);assert.equal(read('publish_posts','post').revision,4);
const linked=read('publish_preparations','linked');assert.equal(linked.source.column,names[1]);
for(const k of ['state','checkedDigest','error','evidence'])assert.deepEqual(linked[k],unknown[k],'原执行状态及证据保持');
const unowned=read('publish_preparations','nosource');assert.equal(unowned.source,undefined);assert.equal(unowned.test,true);assert.equal(unowned.operations[0].actor.sessionId,actor.sessionId);
assert.equal(prepStatus({records:[unowned]}).rows[0].column,names[1]);
assert.equal(reclassifyColumns(db,[{...assignment,expectedColumn:names[1]}],actor).updates.length,0,'同栏目不重复追加日志');
assert.throws(()=>reclassifyColumns(db,[{...assignment,column:'任意新栏目'}],actor),/栏目/);
db.close();console.log('栏目自测通过：白名单、旧入口拒绝、事务回滚、并发校验、关联同步、缺来源不伪造、未知锁与证据保留。');
